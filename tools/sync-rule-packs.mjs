import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPublicKeyFromFile, verifyRulePackPayload } from './rule-pack-crypto.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');
const [sourcePath, extensionDataPath, dataJsPath, publicKeyPathArg] = process.argv.slice(2);

if (!sourcePath || !extensionDataPath || !dataJsPath) {
  console.error('Usage: node sync-rule-packs.mjs <source.json> <extension/data/rule-packs.json> <extension/rule-packs-data.js> [public.pem]');
  process.exit(1);
}

const publicKeyPath = publicKeyPathArg || path.join(projectRoot, 'data', 'rule-pack-public.pem');
const publicRawPath = path.join(projectRoot, 'data', 'rule-pack-public.key');
const json = fs.readFileSync(sourcePath, 'utf8').trim();
const payload = JSON.parse(json);

if (!payload.sig) {
  console.error('Rule pack is missing sig. Run: node tools/sign-rule-pack.mjs');
  process.exit(1);
}

if (!fs.existsSync(publicKeyPath)) {
  console.error(`Missing public key at ${publicKeyPath}`);
  process.exit(1);
}

const publicKey = loadPublicKeyFromFile(publicKeyPath);
if (!verifyRulePackPayload(payload, publicKey)) {
  console.error('Rule pack signature verification failed.');
  process.exit(1);
}

fs.mkdirSync(path.dirname(extensionDataPath), { recursive: true });
fs.writeFileSync(extensionDataPath, `${json}\n`, 'utf8');

const publicRaw = fs.readFileSync(publicRawPath, 'utf8').trim();
const js = [
  '/* Generated by tools/Sync-RulePacks.ps1. Do not edit by hand. */',
  `globalThis.__grandmaGuardRulePacksPublicKey = ${JSON.stringify(publicRaw)};`,
  `globalThis.__grandmaGuardRulePacksBundled = ${json};`,
  ''
].join('\n');
fs.writeFileSync(dataJsPath, js, 'utf8');

console.log(`Wrote ${extensionDataPath}`);
console.log(`Wrote ${dataJsPath}`);
